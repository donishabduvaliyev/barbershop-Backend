const SUPPORTED_LANGUAGES = ['en', 'ru', 'uz'];
const DEFAULT_LANGUAGE = 'uz';

export function normalizeLanguage(lang) {
  return SUPPORTED_LANGUAGES.includes(lang) ? lang : DEFAULT_LANGUAGE;
}

function getPath(obj, path) {
  return path.split('.').reduce((node, part) => (node == null ? undefined : node[part]), obj);
}

// t('ru', 'customer.welcome') or t('ru', 'customer.reminderBody', { shopName: 'X', whenLabel: 'tomorrow' })
export function t(lang, key, vars = {}) {
  const safeLang = normalizeLanguage(lang);
  let template = getPath(DICTIONARY[safeLang], key);
  if (template === undefined) template = getPath(DICTIONARY[DEFAULT_LANGUAGE], key);
  if (template === undefined) return key;

  return Object.entries(vars).reduce(
    (str, [name, value]) => str.replaceAll(`{${name}}`, value ?? ''),
    template
  );
}

export const LANGUAGE_NAMES = {
  en: 'English',
  ru: 'Русский',
  uz: "O'zbekcha",
};

export default { t, normalizeLanguage, LANGUAGE_NAMES };
